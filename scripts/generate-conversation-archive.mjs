export async function generateConversationArchive({
  check = false,
  root = repositoryRoot,
} = {}) {
  const descriptor = await readConversationArchiveDescriptor(root);
  const outputs = {
    [outputPaths.typescript]: generateTypeScript(descriptor),
    [outputPaths.dart]: generateDart(descriptor),
  };
  const drifted = [];

  for (const [path, generated] of Object.entries(outputs)) {
    const absolutePath = resolve(root, path);
    if (check) {
      let existing;
      try {
        existing = await readFile(absolutePath, "utf8");
      } catch (error) {
        if (error?.code !== "ENOENT") throw error;
      }
      if (existing !== generated) drifted.push(path);
      continue;
    }

    await mkdir(dirname(absolutePath), { recursive: true });
    await writeFile(absolutePath, generated, "utf8");
  }

  return drifted;
}

function validateDescriptor(descriptor) {
  if (descriptor?.schemaVersion !== 1) {
    throw new Error("conversation-archive.json must have schemaVersion 1");
  }
  if (descriptor.operation !== "set_conversation_archive") {
    throw new Error("conversation-archive.json must define the archive operation");
  }
  assertNames(
    descriptor.intents,
    ["archive", "restore"],
    "intents",
  );
  const [archiveIntent, restoreIntent] = descriptor.intents;
  if (
    archiveIntent.expectedState !== "active" ||
    archiveIntent.requestedState !== "archived" ||
    restoreIntent.expectedState !== "archived" ||
    restoreIntent.requestedState !== "active"
  ) {
    throw new Error("archive and restore intents must define inverse explicit states");
  }
  assertNames(descriptor.inputFields, expectedInputFields, "input fields");
  assertNames(descriptor.archiveStates, ["active", "archived"], "archive states");
  assertNames(descriptor.resultFields, expectedResultFields, "result fields");
  assertNames(
    descriptor.reconciliationStatuses,
    ["applied", "replayed", "already_requested_state", "lifecycle_conflict"],
    "reconciliation statuses",
  );
  const expectedStatusRules = [
    ["requested", "expectedPlusOne"],
    ["requested", "authoritative"],
    ["requested", "authoritative"],
    ["expected", "differentFromExpected"],
  ];
  descriptor.reconciliationStatuses.forEach((status, index) => {
    const [state, revision] = expectedStatusRules[index];
    if (
      status.authoritativeState !== state ||
      status.revisionRule !== revision
    ) {
      throw new Error(status.name + " has unsupported reconciliation rules");
    }
  });
  if (
    JSON.stringify(descriptor.trustedContextAliases) !==
    JSON.stringify(expectedTrustedAliases)
  ) {
    throw new Error("conversation-archive.json trusted aliases are incomplete");
  }
  const archivedBy = descriptor.archiveStates[1]?.fields?.find(
    (field) => field.name === "archivedByUserId",
  );
  if (archivedBy?.type !== "UserId" || archivedBy.source !== "server") {
    throw new Error("archivedByUserId must be a server-derived UserId");
  }
}

function assertNames(values, expected, label) {
  const names = values?.map((value) => value?.name);
  if (JSON.stringify(names) !== JSON.stringify(expected)) {
    throw new Error(
      "conversation-archive.json must define exactly these " +
        label +
        ": " +
        expected.join(", "),
    );
  }
}

function normalizeAlias(alias) {
  return alias.replaceAll(/[^a-zA-Z0-9]/g, "").toLowerCase();
}

function parseArguments(args) {
  let check = false;
  let root = repositoryRoot;
  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];
    if (argument === "--check") {
      check = true;
    } else if (argument === "--root") {
      const value = args[index + 1];
      if (!value) throw new Error("--root requires a path");
      root = resolve(value);
      index += 1;
    } else {
      throw new Error("Unknown argument: " + argument);
    }
  }
  return { check, root };
}

async function main() {
  const options = parseArguments(process.argv.slice(2));
  const drifted = await generateConversationArchive(options);
  if (options.check && drifted.length > 0) {
    console.error(
      `Generated conversation archive contracts are out of date:\n${drifted
        .map((path) => `- ${relative(options.root, resolve(options.root, path))}`)
        .join("\n")}\nRun npm run generate:conversation-archive.`,
    );
    process.exitCode = 1;
  } else if (options.check) {
    console.log("Generated conversation archive contracts are up to date.");
  }
}

