import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const packageVersionOutputPath = "src/client/generated/package-version.ts";

export async function readPackageVersion(root = repositoryRoot) {
  const manifest = JSON.parse(
    await readFile(resolve(root, "package.json"), "utf8"),
  );
  if (
    typeof manifest.version !== "string" ||
    manifest.version.length === 0 ||
    manifest.version.trim() !== manifest.version
  ) {
    throw new TypeError("package.json version must be a non-empty trimmed string");
  }
  return manifest.version;
}

export function generatePackageVersionSource(version) {
  if (typeof version !== "string" || version.length === 0) {
    throw new TypeError("package version must be a non-empty string");
  }
  return [
    "// Generated by scripts/generate-package-version.mjs from package.json.",
    "// Do not edit this file directly.",
    `export const CHAT_CLIENT_PACKAGE_VERSION = ${JSON.stringify(version)} as const;`,
    "",
  ].join("\n");
}

export async function generatePackageVersion({
  check = false,
  root = repositoryRoot,
} = {}) {
  const generated = generatePackageVersionSource(await readPackageVersion(root));
  const output = resolve(root, packageVersionOutputPath);
  if (check) {
    let existing;
    try {
      existing = await readFile(output, "utf8");
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
    }
    return existing === generated ? [] : [packageVersionOutputPath];
  }

  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, generated, "utf8");
  return [];
}

function parseArguments(args) {
  let check = false;
  let root = repositoryRoot;
  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];
    if (argument === "--check") {
      check = true;
    } else if (argument === "--root") {
      const value = args[index + 1];
      if (!value) throw new Error("--root requires a path");
      root = resolve(value);
      index += 1;
    } else {
      throw new Error(`Unknown argument: ${argument}`);
    }
  }
  return { check, root };
}

async function main() {
  const options = parseArguments(process.argv.slice(2));
  const drifted = await generatePackageVersion(options);
  if (options.check && drifted.length > 0) {
    console.error(
      `Generated package-version source is out of date:\n${drifted
        .map((path) => `- ${relative(options.root, resolve(options.root, path))}`)
        .join("\n")}\nRun npm run generate:package-version.`,
    );
    process.exitCode = 1;
  } else if (options.check) {
    console.log("Generated package-version source is up to date.");
  }
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  await main();
}
