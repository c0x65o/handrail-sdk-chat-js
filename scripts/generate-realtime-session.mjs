function toDartName(value) {
  return value.replace(/_([a-z])/g, (_, letter) => letter.toUpperCase());
}

function escapeDart(value) {
  return value.replaceAll("\\", "\\\\").replaceAll("'", "\\'");
}

function renderDartStringList(values) {
  return `<String>[${values.map((value) => `'${escapeDart(value)}'`).join(", ")}]`;
}

function parseArguments(arguments_) {
  let check = false;
  let root = repositoryRoot;
  for (let index = 0; index < arguments_.length; index += 1) {
    const argument = arguments_[index];
    if (argument === "--check") check = true;
    else if (argument === "--root") {
      const value = arguments_[index + 1];
      if (value === undefined) throw new TypeError("--root requires a path");
      root = resolve(value);
      index += 1;
    } else throw new TypeError(`unknown argument: ${argument}`);
  }
  return { check, root };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const options = parseArguments(process.argv.slice(2));
  const drifted = await generateRealtimeSession(options);
  if (options.check && drifted.length > 0) {
    console.error(
      `Generated realtime session files are stale:\n${drifted
        .map((path) => `- ${relative(options.root, resolve(options.root, path))}`)
        .join("\n")}`,
    );
    process.exitCode = 1;
  } else if (options.check) {
    console.log("Generated realtime session files are up to date.");
  }
}
