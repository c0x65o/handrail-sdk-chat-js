export async function generateDurableEvents({ check = false, root = repositoryRoot } = {}) {
  const descriptor = await readDurableEventsDescriptor(root);
  const outputs = { [outputPaths.typescript]: generateTypeScript(descriptor), [outputPaths.dart]: formatDart(generateDart(descriptor)) };
  const drifted = [];
  for (const [path, generated] of Object.entries(outputs)) {
    const absolute = resolve(root, path);
    if (check) {
      let existing;
      try { existing = await readFile(absolute, "utf8"); } catch (error) { if (error?.code !== "ENOENT") throw error; }
      if (existing !== generated) drifted.push(path);
    } else { await mkdir(dirname(absolute), { recursive: true }); await writeFile(absolute, generated, "utf8"); }
  }
  return drifted;
}

function formatDart(source) {
  const directory = mkdtempSync(join(tmpdir(), "handrail-durable-dart-"));
  const path = join(directory, "durable_events.dart");
  try {
    writeFileSync(path, source, "utf8");
    const dart = process.env.DART_SDK
      ? resolve(process.env.DART_SDK, "bin/dart")
      : "dart";
    const result = spawnSync(dart, ["format", "--language-version=3.3", path], {
      encoding: "utf8",
      env: process.env,
    });
    if (result.status !== 0) {
      throw new Error("The Dart formatter could not format durable_events.dart");
    }
    return readFileSync(path, "utf8");
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}

function validateDescriptor(descriptor) {
  if (descriptor?.schemaVersion !== 1 || descriptor.durability !== "durable") throw new Error("durable-events.json must define schemaVersion 1 durable events");
  if (descriptor.genericEnvelope !== "contracts/realtime/session.json#ChatEvent") throw new Error("durable events must retain the generic ChatEvent envelope");
  const expectedErrors = ["unknown_event_type", "tenant_mismatch", "private_stream_mismatch", "incoherent_payload"];
  if (JSON.stringify(descriptor.strictParserErrorCategories) !== JSON.stringify(expectedErrors)) throw new Error("durable event error categories are invalid");
  if (!Array.isArray(descriptor.events) || descriptor.events.length === 0) throw new Error("durable event registry must not be empty");
  const keys = new Set(); const types = new Set();
  for (const event of descriptor.events) {
    if (!/^[a-z][A-Za-z0-9]*$/.test(event.key) || keys.has(event.key)) throw new Error("durable event keys must be unique camelCase values");
    if (typeof event.type !== "string" || !event.type.includes(".") || types.has(event.type)) throw new Error("durable event types must be unique dotted strings");
    keys.add(event.key); types.add(event.type);
    if (!/^[A-Z][A-Za-z0-9]*Payload$/.test(event.payloadClass) || typeof event.payloadModel !== "string") throw new Error(`durable event ${event.type} has an invalid payload model`);
    if (!Array.isArray(event.streamScopes) || event.streamScopes.length === 0 || event.streamScopes.some((scope) => scope !== "conversation" && scope !== "user_private")) throw new Error(`durable event ${event.type} has an invalid stream scope`);
    if (!Array.isArray(event.requiredFields) || !Array.isArray(event.optionalFields)) throw new Error(`durable event ${event.type} has an invalid payload shape`);
    if (event.entityPath !== undefined && (typeof event.entityPath !== "string" || event.entityPath.trim() === "")) throw new Error(`durable event ${event.type} has an invalid entityPath`);
    if (event.entityPath === undefined && (event.streamScopes.includes("conversation") || typeof event.actorPath !== "string" || !event.requiredFields.includes(event.actorPath))) throw new Error(`durable event ${event.type} requires entityPath or a required private actorPath`);
  }
}

