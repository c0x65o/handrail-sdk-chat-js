import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const descriptorPath = "contracts/models/identifiers.json";
const outputPaths = {
  typescript: "src/contracts/identifiers.ts",
  dart: "contracts/generated/dart/identifiers.dart",
};
const expectedNames = [
  "TenantScopedId",
  "TenantId",
  "ConversationId",
  "MessageId",
  "UserId",
  "AttachmentId",
  "DeviceId",
  "SessionId",
  "IsoTimestamp",
  "MessageSequence",
];

export async function readIdentifierDescriptor(root = repositoryRoot) {
  const source = await readFile(resolve(root, descriptorPath), "utf8");
  const descriptor = JSON.parse(source);
  validateDescriptor(descriptor);
  return descriptor;
}

export function generateTypeScript(descriptor) {
  validateDescriptor(descriptor);

  const lines = [
    "// Generated by scripts/generate-identifiers.mjs from contracts/models/identifiers.json.",
    "// Do not edit this file directly.",
    "",
    "declare const identifierBrand: unique symbol;",
    "",
  ];

  for (const identifier of descriptor.identifiers) {
    lines.push(`/** ${identifier.description} */`);
    switch (identifier.category) {
      case "tenantScopedBase":
        lines.push(
          `export type ${identifier.name}<Kind extends string> = string & {`,
          "  readonly [identifierBrand]: `tenant:${Kind}`;",
          "};",
        );
        break;
      case "tenant":
        lines.push(
          `export type ${identifier.name} = string & {`,
          '  readonly [identifierBrand]: "tenant";',
          "};",
        );
        break;
      case "tenantScoped":
        lines.push(
          `export type ${identifier.name} = TenantScopedId<${JSON.stringify(identifier.scope)}>;`,
        );
        break;
      case "scalar":
        lines.push(
          `export type ${identifier.name} = ${identifier.wireType};`,
        );
        break;
    }
    lines.push("");
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

export function generateDart(descriptor) {
  validateDescriptor(descriptor);

  const lines = [
    "// Generated by scripts/generate-identifiers.mjs from contracts/models/identifiers.json.",
    "// Do not edit this file directly.",
    "",
  ];

  for (const identifier of descriptor.identifiers) {
    switch (identifier.category) {
      case "tenantScopedBase":
        lines.push(...renderTenantScopedBase(identifier));
        break;
      case "tenantScoped":
        lines.push(...renderTenantScopedIdentifier(identifier));
        break;
      case "tenant":
      case "scalar":
        lines.push(
          ...(identifier.wireType === "number"
            ? renderNumberIdentifier(identifier)
            : renderStringIdentifier(identifier)),
        );
        break;
    }
    lines.push("");
  }

  lines.push(
    "String _readString(Object? json, String typeName) {",
    "  if (json is! String) {",
    "    throw FormatException('$typeName must be a string JSON value.');",
    "  }",
    "  return json;",
    "}",
    "",
    "int _readInt(Object? json, String typeName) {",
    "  if (json is! int) {",
    "    throw FormatException('$typeName must be an integer JSON value.');",
    "  }",
    "  return json;",
    "}",
  );

  return `${lines.join("\n").trimEnd()}\n`;
}

export async function generateIdentifiers({ check = false, root = repositoryRoot } = {}) {
  const descriptor = await readIdentifierDescriptor(root);
  const outputs = {
    [outputPaths.typescript]: generateTypeScript(descriptor),
    [outputPaths.dart]: generateDart(descriptor),
  };
  const drifted = [];

  for (const [path, generated] of Object.entries(outputs)) {
    const absolutePath = resolve(root, path);
    if (check) {
      let existing;
      try {
        existing = await readFile(absolutePath, "utf8");
      } catch (error) {
        if (error?.code !== "ENOENT") throw error;
      }
      if (existing !== generated) drifted.push(path);
      continue;
    }

    await mkdir(dirname(absolutePath), { recursive: true });
    await writeFile(absolutePath, generated, "utf8");
  }

  return drifted;
}

function renderTenantScopedBase(identifier) {
  return [
    `/// ${identifier.description}`,
    `base class ${identifier.name} {`,
    `  const ${identifier.name}(this.value);`,
    "",
    `  factory ${identifier.name}.fromJson(Object? json) =>`,
    `      ${identifier.name}(_readString(json, '${identifier.name}'));`,
    "",
    "  final String value;",
    "",
    "  String toJson() => value;",
    "",
    "  @override",
    "  bool operator ==(Object other) =>",
    "      other.runtimeType == runtimeType &&",
    `      other is ${identifier.name} &&`,
    "      other.value == value;",
    "",
    "  @override",
    "  int get hashCode => Object.hash(runtimeType, value);",
    "",
    "  @override",
    "  String toString() => '$runtimeType($value)';",
    "}",
  ];
}

function renderTenantScopedIdentifier(identifier) {
  return [
    `/// ${identifier.description}`,
    `final class ${identifier.name} extends TenantScopedId {`,
    `  const ${identifier.name}(super.value);`,
    "",
    ...renderDartFactory(identifier, "_readString"),
    "}",
  ];
}

function renderStringIdentifier(identifier) {
  return [
    `/// ${identifier.description}`,
    `final class ${identifier.name} {`,
    `  const ${identifier.name}(this.value);`,
    "",
    ...renderDartFactory(identifier, "_readString"),
    "",
    "  final String value;",
    "",
    "  String toJson() => value;",
    "",
    "  @override",
    ...renderDartEquality(identifier),
    "",
    "  @override",
    "  int get hashCode => value.hashCode;",
    "",
    "  @override",
    `  String toString() => '${identifier.name}(\$value)';`,
    "}",
  ];
}

function renderNumberIdentifier(identifier) {
  return [
    `/// ${identifier.description}`,
    `final class ${identifier.name} {`,
    `  const ${identifier.name}(this.value);`,
    "",
    ...renderDartFactory(identifier, "_readInt"),
    "",
    "  final int value;",
    "",
    "  int toJson() => value;",
    "",
    "  @override",
    ...renderDartEquality(identifier),
    "",
    "  @override",
    "  int get hashCode => value.hashCode;",
    "",
    "  @override",
    `  String toString() => '${identifier.name}(\$value)';`,
    "}",
  ];
}

function renderDartFactory(identifier, reader) {
  const declaration = `  factory ${identifier.name}.fromJson(Object? json) =>`;
  const constructor = `${identifier.name}(${reader}(json, '${identifier.name}'));`;
  const singleLine = `${declaration} ${constructor}`;
  return singleLine.length <= 80
    ? [singleLine]
    : [declaration, `      ${constructor}`];
}

function renderDartEquality(identifier) {
  const expression = `bool operator ==(Object other) => other is ${identifier.name} && other.value == value;`;
  return `  ${expression}`.length <= 80
    ? [`  ${expression}`]
    : [
        "  bool operator ==(Object other) =>",
        `      other is ${identifier.name} && other.value == value;`,
      ];
}

function validateDescriptor(descriptor) {
  if (descriptor?.schemaVersion !== 1 || !Array.isArray(descriptor.identifiers)) {
    throw new Error("identifiers.json must contain schemaVersion 1 and an identifiers array");
  }

  const names = descriptor.identifiers.map((identifier) => identifier?.name);
  if (JSON.stringify(names) !== JSON.stringify(expectedNames)) {
    throw new Error(`identifiers.json must define exactly: ${expectedNames.join(", ")}`);
  }

  for (const identifier of descriptor.identifiers) {
    if (typeof identifier.description !== "string" || identifier.description.length === 0) {
      throw new Error(`${identifier.name} must have a description`);
    }
    if (!new Set(["tenantScopedBase", "tenant", "tenantScoped", "scalar"]).has(identifier.category)) {
      throw new Error(`${identifier.name} has an unsupported category`);
    }
    if (!new Set(["string", "number"]).has(identifier.wireType)) {
      throw new Error(`${identifier.name} has an unsupported wireType`);
    }
    if (identifier.category === "tenantScoped" && typeof identifier.scope !== "string") {
      throw new Error(`${identifier.name} must have a tenant scope`);
    }
  }
}

function parseArguments(args) {
  let check = false;
  let root = repositoryRoot;

  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];
    if (argument === "--check") {
      check = true;
    } else if (argument === "--root") {
      const value = args[index + 1];
      if (!value) throw new Error("--root requires a path");
      root = resolve(value);
      index += 1;
    } else {
      throw new Error(`Unknown argument: ${argument}`);
    }
  }

  return { check, root };
}

async function main() {
  const options = parseArguments(process.argv.slice(2));
  const drifted = await generateIdentifiers(options);
  if (options.check && drifted.length > 0) {
    console.error(
      `Generated identifier contracts are out of date:\n${drifted
        .map((path) => `- ${relative(options.root, resolve(options.root, path))}`)
        .join("\n")}\nRun npm run generate:identifiers.`,
    );
    process.exitCode = 1;
  } else if (options.check) {
    console.log("Generated identifier contracts are up to date.");
  }
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  await main();
}
