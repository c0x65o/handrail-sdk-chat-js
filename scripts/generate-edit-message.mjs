export async function readEditMessageDescriptor(root = repositoryRoot) {
  const source = await readFile(resolve(root, descriptorPath), "utf8");
  const descriptor = JSON.parse(source);
  validateDescriptor(descriptor);
  return descriptor;
}

export function generateTypeScript(descriptor) {
  validateDescriptor(descriptor);
  const operation = JSON.stringify(descriptor.operation);
  const trustedNormalized = descriptor.trustedIdentityAliases
    .map(normalizeAlias)
    .map((alias) => `  ${JSON.stringify(alias)},`)
    .join("\n");
  const inputKeys = descriptor.inputFields
    .map((field) => `  ${JSON.stringify(field.name)},`)
    .join("\n");
  const resultKeys = descriptor.resultFields
    .map((field) => `  ${JSON.stringify(field.name)},`)
    .join("\n");

  return `// Generated by scripts/generate-edit-message.mjs from contracts/http/edit-message.json.
// Do not edit this file directly.

import type { MessageId } from "../identifiers.js";
import type { Message, MessageBlock, MessageContent } from "../message.js";
import {
  MessageMutationParseError,
  parseSendMessageInput,
  parseSendMessageResult,
} from "./send-message.js";
import type {
  MessageMutationParseErrorCode,
  MessageMutationReconciliationStatus,
  NoTrustedMessageMutationIdentity,
} from "./send-message.js";

const TRUSTED_IDENTITY_FIELDS = new Set([
${trustedNormalized}
]);

const INPUT_KEYS = [
${inputKeys}
] as const;

const RESULT_KEYS = [
${resultKeys}
] as const;

/** Content-only edit; the original reply target and notification choice are immutable. */
export interface EditMessageInput<Block extends MessageBlock = MessageBlock>
  extends NoTrustedMessageMutationIdentity {
  readonly operation: ${operation};
  readonly messageId: MessageId;
  readonly expectedRevision: number;
  readonly content: MessageContent<Block>;
  readonly idempotencyKey: string;
  readonly replyTo?: never;
}

interface EditMessageResultBase<
  Block extends MessageBlock,
  Status extends MessageMutationReconciliationStatus | "revision_conflict",
> {
  readonly operation: ${operation};
  readonly reconciliationStatus: Status;
  /** Exact echo of the optimistic-concurrency revision supplied by the caller. */
  readonly expectedRevision: number;
  /** Full canonical Message, including its original optional replyTo in every status. */
  readonly message: Message<Block>;
  /** Current authoritative revision; always equal to message.revision.revision. */
  readonly canonicalRevision: number;
}

type EditMessageSuccess<Block extends MessageBlock> = EditMessageResultBase<
  Block,
  MessageMutationReconciliationStatus
>;

type EditMessageConflict<Block extends MessageBlock> = EditMessageResultBase<
  Block,
  "revision_conflict"
>;

export type EditMessageResult<Block extends MessageBlock = MessageBlock> =
  | EditMessageSuccess<Block>
  | EditMessageConflict<Block>;

export function parseEditMessageInput<Block extends MessageBlock = MessageBlock>(
  value: unknown,
): EditMessageInput<Block> {
  const input = requireRecord(value, "input", "malformed_input");
  rejectTrustedIdentityFields(input);
  assertExactKeys(input, INPUT_KEYS, "input", "malformed_input");
  if (input.operation !== ${operation}) {
    throw mutationError("malformed_input", "operation must be ${descriptor.operation}");
  }

  const idempotencyKey = readNonBlankString(
    input.idempotencyKey,
    "input.idempotencyKey",
    "malformed_input",
  );
  const content = parseSendMessageInput<Block>({
    operation: "send",
    conversationId: "edit-content-validation",
    content: input.content,
    clientMessageId: "edit-content-validation",
    idempotencyKey,
  }).content;

  return {
    operation: ${operation},
    messageId: readNonBlankString(
      input.messageId,
      "input.messageId",
      "malformed_input",
    ) as MessageId,
    expectedRevision: readPositiveSafeInteger(
      input.expectedRevision,
      "input.expectedRevision",
      "malformed_input",
    ),
    content,
    idempotencyKey,
  };
}

export function parseEditMessageResult<
  Block extends MessageBlock = MessageBlock,
>(value: unknown): EditMessageResult<Block> {
  const result = requireRecord(value, "result", "malformed_result");
  assertExactKeys(result, RESULT_KEYS, "result", "malformed_result");
  if (result.operation !== ${operation}) {
    throw mutationError("malformed_result", "operation must be ${descriptor.operation}");
  }

  const expectedRevision = readPositiveSafeInteger(
    result.expectedRevision,
    "result.expectedRevision",
    "malformed_result",
  );
  const canonicalRevision = readPositiveSafeInteger(
    result.canonicalRevision,
    "result.canonicalRevision",
    "malformed_result",
  );
  const messageRecord = requireRecord(
    result.message,
    "result.message",
    "malformed_result",
  );
  const revisionRecord = requireRecord(
    messageRecord.revision,
    "result.message.revision",
    "malformed_result",
  );
  const messageRevision = readPositiveSafeInteger(
    revisionRecord.revision,
    "result.message.revision.revision",
    "malformed_result",
  );
  if (canonicalRevision !== messageRevision) {
    throw mutationError(
      "revision_mismatch",
      "canonicalRevision must equal message.revision.revision",
    );
  }

  // Reuse the canonical generated Message validator while neutralizing the
  // send-only revision-one invariant in its surrounding mutation envelope.
  // This also validates optional replyTo; return the original full Message below
  // to preserve reply identity, notification choice, and the actual revision.
  parseSendMessageResult<Block>({
    operation: "send",
    reconciliationStatus: "applied",
    clientMessageId: "edit-message-validation",
    message: {
      ...messageRecord,
      revision: { ...revisionRecord, revision: 1 },
    },
    canonicalRevision: 1,
  });
  const message = messageRecord as unknown as Message<Block>;

  if (result.reconciliationStatus === "revision_conflict") {
    if (canonicalRevision === expectedRevision) {
      throw mutationError(
        "revision_mismatch",
        "a revision conflict must report a different canonical revision",
      );
    }
    return {
      operation: ${operation},
      reconciliationStatus: "revision_conflict",
      expectedRevision,
      message,
      canonicalRevision,
    };
  }

  const reconciliationStatus = readSuccessStatus(result.reconciliationStatus);
  if (canonicalRevision !== expectedRevision + 1) {
    throw mutationError(
      "revision_mismatch",
      "a successful edit must advance expectedRevision by exactly one",
    );
  }
  if (Object.hasOwn(messageRecord, "deletedAt")) {
    throw mutationError(
      "malformed_result",
      "a successful edit result must contain an active message",
    );
  }
  return {
    operation: ${operation},
    reconciliationStatus,
    expectedRevision,
    message,
    canonicalRevision,
  };
}

function rejectTrustedIdentityFields(input: Record<string, unknown>): void {
  for (const key of Object.keys(input)) {
    const normalizedKey = key.replaceAll(/[^a-zA-Z0-9]/g, "").toLowerCase();
    if (TRUSTED_IDENTITY_FIELDS.has(normalizedKey)) {
      throw mutationError(
        "trusted_identity_field",
        "input." + key + " is server-derived and cannot be supplied by a client",
      );
    }
  }
}

function readSuccessStatus(
  value: unknown,
): MessageMutationReconciliationStatus {
  if (value !== "applied" && value !== "replayed") {
    throw mutationError(
      "malformed_result",
      "reconciliationStatus must be applied, replayed, or revision_conflict",
    );
  }
  return value;
}

function assertExactKeys(
  value: Record<string, unknown>,
  expected: readonly string[],
  path: string,
  code: "malformed_input" | "malformed_result",
): void {
  const expectedSet = new Set(expected);
  for (const key of Object.keys(value)) {
    if (!expectedSet.has(key)) {
      throw mutationError(code, path + "." + key + " is not supported");
    }
  }
  for (const key of expected) {
    if (!Object.hasOwn(value, key)) {
      throw mutationError(code, path + "." + key + " is required");
    }
  }
}

function requireRecord(
  value: unknown,
  path: string,
  code: "malformed_input" | "malformed_result",
): Record<string, unknown> {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    throw mutationError(code, path + " must be an object");
  }
  return value as Record<string, unknown>;
}

function readNonBlankString(
  value: unknown,
  path: string,
  code: "malformed_input" | "malformed_result",
): string {
  if (typeof value !== "string" || value.trim().length === 0) {
    throw mutationError(code, path + " must be a non-blank string");
  }
  return value;
}

function readPositiveSafeInteger(
  value: unknown,
  path: string,
  code: "malformed_input" | "malformed_result",
): number {
  if (!Number.isSafeInteger(value) || (value as number) < 1) {
    throw mutationError(code, path + " must be a positive safe integer");
  }
  return value as number;
}

function mutationError(
  code: MessageMutationParseErrorCode,
  message: string,
): MessageMutationParseError {
  return new MessageMutationParseError(code, message);
}
`;
}

export function generateDart(descriptor) {
  validateDescriptor(descriptor);
  const operation = descriptor.operation;
  const trustedNormalized = descriptor.trustedIdentityAliases
    .map(normalizeAlias)
    .map((alias) => `  '${alias}',`)
    .join("\n");
  const inputKeys = descriptor.inputFields
    .map((field) => `        '${field.name}',`)
    .join("\n");
  const resultKeys = descriptor.resultFields
    .map((field) => `        '${field.name}',`)
    .join("\n");

  return `// Generated by scripts/generate-edit-message.mjs from contracts/http/edit-message.json.
// Do not edit this file directly.

import 'identifiers.dart';
import 'message.dart';

const _trustedIdentityFields = <String>{
${trustedNormalized}
};
const _maxSafeInteger = 9007199254740991;

enum EditMessageReconciliationStatus {
  applied('applied'),
  replayed('replayed'),
  revisionConflict('revision_conflict');

  const EditMessageReconciliationStatus(this.wireValue);

  factory EditMessageReconciliationStatus.fromJson(Object? json) =>
      switch (json) {
        'applied' => EditMessageReconciliationStatus.applied,
        'replayed' => EditMessageReconciliationStatus.replayed,
        'revision_conflict' => EditMessageReconciliationStatus.revisionConflict,
        _ => throw const EditMessageFormatException(
            EditMessageParseErrorCode.malformedResult,
            'EditMessageResult.reconciliationStatus is unsupported.',
          ),
      };

  final String wireValue;
  String toJson() => wireValue;
}

enum EditMessageParseErrorCode {
  malformedInput,
  trustedIdentityField,
  malformedContent,
  malformedResult,
  revisionMismatch,
}

final class EditMessageFormatException extends FormatException {
  const EditMessageFormatException(this.code, String message) : super(message);

  final EditMessageParseErrorCode code;
}

/// Content-only edit; the original reply target and notification choice are immutable.
final class EditMessageRequest {
  const EditMessageRequest({
    required this.messageId,
    required this.expectedRevision,
    required this.content,
    required this.idempotencyKey,
  });

  factory EditMessageRequest.fromJson(Object? json) {
    final object = _readObject(
      json,
      'EditMessageRequest',
      EditMessageParseErrorCode.malformedInput,
    );
    _rejectTrustedIdentityFields(object);
    _ensureExactFields(
      object,
      const {
${inputKeys}
      },
      'EditMessageRequest',
      EditMessageParseErrorCode.malformedInput,
    );
    if (object['operation'] != '${operation}') {
      throw const EditMessageFormatException(
        EditMessageParseErrorCode.malformedInput,
        'EditMessageRequest.operation must be ${operation}.',
      );
    }

    MessageContent content;
    try {
      content = MessageContent.fromJson(object['content']);
    } on FormatException catch (error) {
      throw EditMessageFormatException(
        EditMessageParseErrorCode.malformedContent,
        'EditMessageRequest.content is malformed: \${error.message}',
      );
    }
    return EditMessageRequest(
      messageId: MessageId(
        _readNonBlankString(
          object['messageId'],
          'EditMessageRequest.messageId',
          EditMessageParseErrorCode.malformedInput,
        ),
      ),
      expectedRevision: _readPositiveSafeInteger(
        object['expectedRevision'],
        'EditMessageRequest.expectedRevision',
        EditMessageParseErrorCode.malformedInput,
      ),
      content: content,
      idempotencyKey: _readNonBlankString(
        object['idempotencyKey'],
        'EditMessageRequest.idempotencyKey',
        EditMessageParseErrorCode.malformedInput,
      ),
    );
  }

  String get operation => '${operation}';
  final MessageId messageId;
  final int expectedRevision;
  final MessageContent content;
  final String idempotencyKey;

  Map<String, Object?> toJson() => {
        'operation': operation,
        'messageId': messageId.toJson(),
        'expectedRevision': expectedRevision,
        'content': content.toJson(),
        'idempotencyKey': idempotencyKey,
      };
}

final class EditMessageResult {
  const EditMessageResult({
    required this.reconciliationStatus,
    required this.expectedRevision,
    required this.message,
    required this.canonicalRevision,
  });

  factory EditMessageResult.fromJson(Object? json) {
    final object = _readObject(
      json,
      'EditMessageResult',
      EditMessageParseErrorCode.malformedResult,
    );
    _ensureExactFields(
      object,
      const {
${resultKeys}
      },
      'EditMessageResult',
      EditMessageParseErrorCode.malformedResult,
    );
    if (object['operation'] != '${operation}') {
      throw const EditMessageFormatException(
        EditMessageParseErrorCode.malformedResult,
        'EditMessageResult.operation must be ${operation}.',
      );
    }

    final expectedRevision = _readPositiveSafeInteger(
      object['expectedRevision'],
      'EditMessageResult.expectedRevision',
      EditMessageParseErrorCode.malformedResult,
    );
    final canonicalRevision = _readPositiveSafeInteger(
      object['canonicalRevision'],
      'EditMessageResult.canonicalRevision',
      EditMessageParseErrorCode.malformedResult,
    );
    Message message;
    try {
      // Canonical Message validation also validates and retains optional replyTo.
      message = Message.fromJson(object['message']);
    } on FormatException catch (error) {
      throw EditMessageFormatException(
        EditMessageParseErrorCode.malformedResult,
        'EditMessageResult.message is malformed: \${error.message}',
      );
    }
    if (canonicalRevision != message.revision.revision) {
      throw const EditMessageFormatException(
        EditMessageParseErrorCode.revisionMismatch,
        'canonicalRevision must equal message.revision.revision.',
      );
    }

    final status = EditMessageReconciliationStatus.fromJson(
      object['reconciliationStatus'],
    );
    if (status == EditMessageReconciliationStatus.revisionConflict) {
      if (canonicalRevision == expectedRevision) {
        throw const EditMessageFormatException(
          EditMessageParseErrorCode.revisionMismatch,
          'A revision conflict must report a different canonical revision.',
        );
      }
    } else {
      if (canonicalRevision != expectedRevision + 1) {
        throw const EditMessageFormatException(
          EditMessageParseErrorCode.revisionMismatch,
          'A successful edit must advance expectedRevision by exactly one.',
        );
      }
      if (message is! ActiveMessage) {
        throw const EditMessageFormatException(
          EditMessageParseErrorCode.malformedResult,
          'A successful edit result must contain an active message.',
        );
      }
    }

    return EditMessageResult(
      reconciliationStatus: status,
      expectedRevision: expectedRevision,
      message: message,
      canonicalRevision: canonicalRevision,
    );
  }

  String get operation => '${operation}';
  final EditMessageReconciliationStatus reconciliationStatus;
  final int expectedRevision;
  /// Full canonical Message, including its original optional replyTo in every status.
  final Message message;
  final int canonicalRevision;

  Map<String, Object?> toJson() => {
        'operation': operation,
        'reconciliationStatus': reconciliationStatus.toJson(),
        'expectedRevision': expectedRevision,
        'message': message.toJson(),
        'canonicalRevision': canonicalRevision,
      };
}

void _rejectTrustedIdentityFields(Map<String, Object?> input) {
  for (final key in input.keys) {
    final normalized = key.replaceAll(RegExp('[^a-zA-Z0-9]'), '').toLowerCase();
    if (_trustedIdentityFields.contains(normalized)) {
      throw EditMessageFormatException(
        EditMessageParseErrorCode.trustedIdentityField,
        'EditMessageRequest.$key is server-derived and cannot be supplied by a client.',
      );
    }
  }
}

Map<String, Object?> _readObject(
  Object? value,
  String path,
  EditMessageParseErrorCode code,
) {
  if (value is! Map<String, Object?>) {
    throw EditMessageFormatException(code, '$path must be a JSON object.');
  }
  return value;
}

void _ensureExactFields(
  Map<String, Object?> object,
  Set<String> expected,
  String path,
  EditMessageParseErrorCode code,
) {
  for (final key in object.keys) {
    if (!expected.contains(key)) {
      throw EditMessageFormatException(code, '$path.$key is not supported.');
    }
  }
  for (final key in expected) {
    if (!object.containsKey(key)) {
      throw EditMessageFormatException(code, '$path.$key is required.');
    }
  }
}

String _readNonBlankString(
  Object? value,
  String path,
  EditMessageParseErrorCode code,
) {
  if (value is! String || value.trim().isEmpty) {
    throw EditMessageFormatException(code, '$path must be a non-blank string.');
  }
  return value;
}

int _readPositiveSafeInteger(
  Object? value,
  String path,
  EditMessageParseErrorCode code,
) {
  if (value is! int || value < 1 || value > _maxSafeInteger) {
    throw EditMessageFormatException(
      code,
      '$path must be a positive safe integer.',
    );
  }
  return value;
}
`;
}

export async function generateEditMessage({
  check = false,
  root = repositoryRoot,
} = {}) {
  const descriptor = await readEditMessageDescriptor(root);
  const outputs = {
    [outputPaths.typescript]: generateTypeScript(descriptor),
    [outputPaths.dart]: generateDart(descriptor),
  };
  const drifted = [];

  for (const [path, generated] of Object.entries(outputs)) {
    const absolutePath = resolve(root, path);
    if (check) {
      let existing;
      try {
        existing = await readFile(absolutePath, "utf8");
      } catch (error) {
        if (error?.code !== "ENOENT") throw error;
      }
      if (existing !== generated) drifted.push(path);
      continue;
    }
    await mkdir(dirname(absolutePath), { recursive: true });
    await writeFile(absolutePath, generated, "utf8");
  }
  return drifted;
}

function validateDescriptor(descriptor) {
  if (descriptor?.schemaVersion !== 1) {
    throw new Error("edit-message.json must have schemaVersion 1");
  }
  if (
    descriptor.method !== "PATCH" ||
    descriptor.path !== "/messages/:messageId" ||
    descriptor.operation !== "edit"
  ) {
    throw new Error("edit-message.json must define PATCH edit-message routing");
  }
  assertNames(descriptor.inputFields, expectedInputFields, "input fields");
  assertNames(descriptor.resultFields, expectedResultFields, "result fields");
  if (
    descriptor.replyTo?.request !== "forbidden" ||
    descriptor.replyTo?.result !== "preserveCanonicalMessage"
  ) {
    throw new Error("edit-message.json must forbid replyTo edits and preserve canonical replyTo results");
  }
  assertNames(
    descriptor.reconciliationStatuses,
    ["applied", "replayed", "revision_conflict"],
    "reconciliation statuses",
  );
  const expectedRules = [
    ["committedReplacement", "expectedPlusOne"],
    ["storedAppliedResult", "expectedPlusOne"],
    ["currentServerMessage", "differentFromExpected"],
  ];
  descriptor.reconciliationStatuses.forEach((status, index) => {
    const [canonicalState, revisionRule] = expectedRules[index];
    if (
      status.canonicalState !== canonicalState ||
      status.revisionRule !== revisionRule
    ) {
      throw new Error(status.name + " has unsupported reconciliation rules");
    }
  });
  if (descriptor.canonicalRevisionRule !== "equalsMessageRevision") {
    throw new Error("edit-message.json must tie canonical and message revisions");
  }
  if (
    descriptor.staleRevisionConflict?.status !== "revision_conflict" ||
    JSON.stringify(descriptor.staleRevisionConflict.carries) !==
      JSON.stringify(["message", "canonicalRevision"]) ||
    descriptor.staleRevisionConflict.canonicalRevisionRule !==
      "differentFromExpectedRevision"
  ) {
    throw new Error("edit-message.json must define deterministic stale conflicts");
  }
  if (
    descriptor.inputFields[3]?.intent !== "replacement" ||
    descriptor.resultFields[2]?.source !== "requestEcho" ||
    descriptor.resultFields[3]?.type !== "Message" ||
    descriptor.resultFields[3]?.source !== "server" ||
    descriptor.resultFields[4]?.type !== "positiveSafeInteger" ||
    descriptor.resultFields[4]?.source !== "server"
  ) {
    throw new Error("edit-message.json must define replacement and canonical ownership");
  }
  if (
    JSON.stringify(descriptor.trustedIdentityAliases) !==
    JSON.stringify(expectedTrustedAliases)
  ) {
    throw new Error("edit-message.json trusted identity aliases are incomplete");
  }
}

function assertNames(values, expected, label) {
  const names = values?.map((value) => value?.name);
  if (JSON.stringify(names) !== JSON.stringify(expected)) {
    throw new Error(
      "edit-message.json must define exactly these " +
        label +
        ": " +
        expected.join(", "),
    );
  }
}

function normalizeAlias(alias) {
  return alias.replaceAll(/[^a-zA-Z0-9]/g, "").toLowerCase();
}

function parseArguments(args) {
  let check = false;
  let root = repositoryRoot;
  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];
    if (argument === "--check") {
      check = true;
    } else if (argument === "--root") {
      const value = args[index + 1];
      if (!value) throw new Error("--root requires a path");
      root = resolve(value);
      index += 1;
    } else {
      throw new Error("Unknown argument: " + argument);
    }
  }
  return { check, root };
}

async function main() {
  const options = parseArguments(process.argv.slice(2));
  const drifted = await generateEditMessage(options);
  if (options.check && drifted.length > 0) {
    console.error(
      `Generated edit-message contracts are out of date:\n${drifted
        .map((path) => `- ${relative(options.root, resolve(options.root, path))}`)
        .join("\n")}\nRun npm run generate:edit-message.`,
    );
    process.exitCode = 1;
  } else if (options.check) {
    console.log("Generated edit-message contracts are up to date.");
  }
}

if (
  process.argv[1] &&
  pathToFileURL(resolve(process.argv[1])).href === import.meta.url
) {
  await main();
}
