import { readFileSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const descriptorPath = "contracts/http/conversation-membership.json";
const outputPaths = {
  typescript: "src/contracts/conversation-membership.ts",
  dart: "contracts/generated/dart/conversation_membership.dart",
};
const templatePaths = {
  typescript: resolve(repositoryRoot, "scripts/templates/conversation-membership.ts.tpl"),
  dart: resolve(repositoryRoot, "scripts/templates/conversation_membership.dart.tpl"),
};
const expectedIntents = [
  "join", "leave", "add_member", "remove_member", "change_member_role",
];
const expectedStatuses = [
  "applied", "replayed", "already_requested_state",
  "member_list_conflict", "safety_rejected",
];
const expectedRoles = ["owner", "moderator", "member"];
const expectedStates = ["active", "left", "removed"];
const expectedSafetyErrors = ["last_owner", "last_active_member"];
const requiredTrustedAliases = [
  "tenant", "tenantId", "organization", "organizationId", "actor", "actorId",
  "actorContext", "actorRole", "actorRoles", "actorUserId", "currentActor",
  "currentActorId", "currentUser", "currentUserId", "user", "userId",
  "principal", "principalId", "subject", "subjectId", "authenticatedUser",
  "authenticatedUserId", "identity", "session", "sessionId", "auth",
  "authorization", "role", "roles", "capability", "capabilities",
  "permission", "permissions", "visibility", "visibilityAuthorization",
  "entity", "entityId", "entityType", "hostEntity", "hostEntityId",
  "hostEntityType", "hostEntityAuthorization",
];

export async function readConversationMembershipDescriptor(root = repositoryRoot) {
  const descriptor = JSON.parse(
    await readFile(resolve(root, descriptorPath), "utf8"),
  );
  validateDescriptor(descriptor);
  return descriptor;
}

export function generateTypeScript(descriptor) {
  validateDescriptor(descriptor);
  return `// Generated by scripts/generate-conversation-membership.mjs from contracts/http/conversation-membership.json.\n// Do not edit this file directly.\n\n${readFileSync(templatePaths.typescript, "utf8")}`;
}

export function generateDart(descriptor) {
  validateDescriptor(descriptor);
  return `// Generated by scripts/generate-conversation-membership.mjs from contracts/http/conversation-membership.json.\n// Do not edit this file directly.\n\n${readFileSync(templatePaths.dart, "utf8")}`;
}

export async function generateConversationMembership({
  check = false,
  root = repositoryRoot,
} = {}) {
  const descriptor = await readConversationMembershipDescriptor(root);
  const outputs = {
    [outputPaths.typescript]: generateTypeScript(descriptor),
    [outputPaths.dart]: generateDart(descriptor),
  };
  const drifted = [];
  for (const [path, generated] of Object.entries(outputs)) {
    const absolutePath = resolve(root, path);
    if (check) {
      let existing;
      try {
        existing = await readFile(absolutePath, "utf8");
      } catch (error) {
        if (error?.code !== "ENOENT") throw error;
      }
      if (existing !== generated) drifted.push(path);
    } else {
      await mkdir(dirname(absolutePath), { recursive: true });
      await writeFile(absolutePath, generated, "utf8");
    }
  }
  return drifted;
}

function validateDescriptor(descriptor) {
  if (descriptor?.version !== 1 || descriptor.operation !== "mutate_conversation_membership") {
    throw new Error("conversation-membership.json must define version 1 of mutate_conversation_membership");
  }
  assertNames(descriptor.intents, expectedIntents, "intents");
  assertNames(descriptor.reconciliationStatuses, expectedStatuses, "reconciliation statuses");
  assertNames(descriptor.safetyErrors, expectedSafetyErrors, "safety errors", "code");
  assertValues(descriptor.memberRow?.roles, expectedRoles, "member roles");
  assertValues(descriptor.memberRow?.states, expectedStates, "member states");
  assertValues(descriptor.trustedContextAliases, requiredTrustedAliases, "trusted context aliases");
  const shapes = descriptor.intents.map(({ targetUserId, requestedRole }) => [targetUserId, requestedRole]);
  const expectedShapes = [
    ["forbidden", "forbidden"], ["forbidden", "forbidden"],
    ["required", "required"], ["required", "forbidden"],
    ["required", "required"],
  ];
  if (JSON.stringify(shapes) !== JSON.stringify(expectedShapes)) {
    throw new Error("conversation-membership.json intent target/role shapes are incompatible");
  }
  if (
    descriptor.idempotencyKey?.maximumUtf8Bytes !== 255 ||
    descriptor.memberRow?.complete !== true ||
    descriptor.memberRow?.uniqueBy !== "userId" ||
    descriptor.memberRow?.canonicalOrder !== "ascendingUtf16CodeUnits" ||
    descriptor.coherenceRules?.resultIntentMatchesRequest !== true ||
    descriptor.coherenceRules?.resultTargetAndRoleMatchRequest !== true
  ) {
    throw new Error("conversation-membership.json is missing required wire invariants");
  }
}

function assertNames(values, expected, label, key = "name") {
  assertValues(values?.map((value) => value?.[key]), expected, label);
}

function assertValues(values, expected, label) {
  if (JSON.stringify(values) !== JSON.stringify(expected)) {
    throw new Error(`conversation-membership.json must define exactly these ${label}: ${expected.join(", ")}`);
  }
}

function parseArguments(args) {
  let check = false;
  let root = repositoryRoot;
  for (let index = 0; index < args.length; index += 1) {
    if (args[index] === "--check") check = true;
    else if (args[index] === "--root") {
      if (!args[index + 1]) throw new Error("--root requires a path");
      root = resolve(args[++index]);
    } else throw new Error(`Unknown argument: ${args[index]}`);
  }
  return { check, root };
}

async function main() {
  const options = parseArguments(process.argv.slice(2));
  const drifted = await generateConversationMembership(options);
  if (options.check && drifted.length > 0) {
    console.error(`Generated conversation membership contracts are out of date:\n${drifted.map((path) => `- ${relative(options.root, resolve(options.root, path))}`).join("\n")}\nRun npm run generate:conversation-membership.`);
    process.exitCode = 1;
  } else if (options.check) {
    console.log("Generated conversation membership contracts are up to date.");
  }
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  await main();
}
