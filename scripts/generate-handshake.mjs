import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const descriptorPath = "contracts/realtime/handshake.json";
const outputPaths = {
  typescript: "src/contracts/generated/realtime-handshake.ts",
  dart: "contracts/generated/dart/realtime_handshake.dart",
};
const expectedTypes = [
  {
    name: "EnabledFeatures",
    kind: "map",
    fields: [],
  },
  {
    name: "SupportedProtocolRange",
    kind: "object",
    fields: ["minimumVersion", "maximumVersion"],
  },
  {
    name: "ServerHandshakeMetadata",
    kind: "object",
    fields: [
      "packageVersion",
      "protocolVersion",
      "schemaVersion",
      "enabledFeatures",
      "supportedProtocolRange",
    ],
  },
  {
    name: "ServerHandshakeMetadataInput",
    kind: "object",
    fields: [
      "packageVersion",
      "protocolVersion",
      "schemaVersion",
      "enabledFeatures",
    ],
  },
];
const scalarTypes = new Set(["string", "integer", "boolean"]);

export async function readHandshakeDescriptor(root = repositoryRoot) {
  const source = await readFile(resolve(root, descriptorPath), "utf8");
  const descriptor = JSON.parse(source);
  validateDescriptor(descriptor);
  return descriptor;
}

export function generateTypeScript(descriptor) {
  validateDescriptor(descriptor);

  const lines = [
    "// Generated by scripts/generate-handshake.mjs from contracts/realtime/handshake.json.",
    "// Do not edit this file directly.",
    "",
  ];

  lines.push("/** Reserved deployment availability flags; absent means false, never authorization. */",
    "export const CHAT_REPLY_THREAD_FEATURES = Object.freeze({",
    ...Object.entries(descriptor.reservedFeatures).map(([key, value]) => `  ${key}: ${JSON.stringify(value)},`),
    "} as const);",
    "export type ChatReplyThreadFeature = (typeof CHAT_REPLY_THREAD_FEATURES)[keyof typeof CHAT_REPLY_THREAD_FEATURES];",
    "");

  for (const type of descriptor.types) {
    lines.push(`/** ${type.description} */`);
    if (type.kind === "map") {
      lines.push(
        `export type ${type.name}${renderTypeScriptParameters(type)} = Readonly<`,
        `  Record<${toTypeScriptType(type.keyType)}, ${toTypeScriptType(type.valueType)}>`,
        ">;",
      );
    } else {
      lines.push(
        `export interface ${type.name}${renderTypeScriptParameters(type)} {`,
      );
      for (const field of type.fields) {
        lines.push(
          `  readonly ${field.name}: ${toTypeScriptType(field.type)}${
            field.typeArgument === undefined ? "" : `<${field.typeArgument}>`
          };`,
        );
      }
      lines.push("}");
    }
    lines.push("");
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

export function generateDart(descriptor) {
  validateDescriptor(descriptor);

  const lines = [
    "// Generated by scripts/generate-handshake.mjs from contracts/realtime/handshake.json.",
    "// Do not edit this file directly.",
    "",
  ];

  lines.push("/// Reserved deployment availability flags; absent means false, never authorization.",
    "abstract final class ChatReplyThreadFeatures {",
    ...Object.entries(descriptor.reservedFeatures).map(([key, value]) => `  static const ${key} = '${value}';`),
    "}", "");

  for (const type of descriptor.types) {
    lines.push(
      ...(type.kind === "map"
        ? renderDartFeatureMap(type)
        : renderDartObject(type)),
      "",
    );
  }

  lines.push(
    "Map<String, Object?> _readObject(Object? json, String typeName) {",
    "  if (json is! Map<Object?, Object?>) {",
    "    throw FormatException('$typeName must be a JSON object.');",
    "  }",
    "",
    "  final object = <String, Object?>{};",
    "  for (final entry in json.entries) {",
    "    final key = entry.key;",
    "    if (key is! String) {",
    "      throw FormatException('$typeName keys must be strings.');",
    "    }",
    "    object[key] = entry.value;",
    "  }",
    "  return object;",
    "}",
    "",
    "Object? _readRequired(",
    "  Map<String, Object?> json,",
    "  String field,",
    "  String typeName,",
    ") {",
    "  if (!json.containsKey(field)) {",
    "    throw FormatException('$typeName.$field is required.');",
    "  }",
    "  return json[field];",
    "}",
    "",
    "String _readString(Object? json, String fieldName) {",
    "  if (json is! String) {",
    "    throw FormatException('$fieldName must be a string JSON value.');",
    "  }",
    "  return json;",
    "}",
    "",
    "int _readInt(Object? json, String fieldName) {",
    "  if (json is! int) {",
    "    throw FormatException('$fieldName must be an integer JSON value.');",
    "  }",
    "  return json;",
    "}",
    "",
    "bool _readBool(Object? json, String fieldName) {",
    "  if (json is! bool) {",
    "    throw FormatException('$fieldName must be a boolean JSON value.');",
    "  }",
    "  return json;",
    "}",
  );

  return `${lines.join("\n").trimEnd()}\n`;
}

export async function generateHandshake({ check = false, root = repositoryRoot } = {}) {
  const descriptor = await readHandshakeDescriptor(root);
  const outputs = {
    [outputPaths.typescript]: generateTypeScript(descriptor),
    [outputPaths.dart]: generateDart(descriptor),
  };
  const drifted = [];

  for (const [path, generated] of Object.entries(outputs)) {
    const absolutePath = resolve(root, path);
    if (check) {
      let existing;
      try {
        existing = await readFile(absolutePath, "utf8");
      } catch (error) {
        if (error?.code !== "ENOENT") throw error;
      }
      if (existing !== generated) drifted.push(path);
      continue;
    }

    await mkdir(dirname(absolutePath), { recursive: true });
    await writeFile(absolutePath, generated, "utf8");
  }

  return drifted;
}

function renderTypeScriptParameters(type) {
  if (type.typeParameters === undefined) return "";
  return `<${type.typeParameters
    .map(
      (parameter) =>
        `${parameter.name} extends ${parameter.constraint} = ${parameter.default}`,
    )
    .join(", ")}>`;
}

function toTypeScriptType(type) {
  switch (type) {
    case "integer":
      return "number";
    case "boolean":
    case "string":
      return type;
    default:
      return type;
  }
}

function renderDartFeatureMap(type) {
  return [
    `/// ${type.description}`,
    `final class ${type.name} {`,
    `  ${type.name}(Map<String, bool> values)`,
    "      : values = Map<String, bool>.unmodifiable(values);",
    "",
    `  factory ${type.name}.fromJson(Object? json) {`,
    `    final object = _readObject(json, '${type.name}');`,
    `    return ${type.name}(`,
    "      object.map(",
    "        (feature, value) => MapEntry(",
    "          feature,",
    `          _readBool(value, '${type.name}.$feature'),`,
    "        ),",
    "      ),",
    "    );",
    "  }",
    "",
    "  final Map<String, bool> values;",
    "",
    "  bool? operator [](String feature) => values[feature];",
    "",
    "  Map<String, bool> toJson() => Map<String, bool>.from(values);",
    "}",
  ];
}

function renderDartObject(type) {
  const lines = [
    `/// ${type.description}`,
    `final class ${type.name} {`,
    `  const ${type.name}({`,
    ...type.fields.map((field) => `    required this.${field.name},`),
    "  });",
    "",
    `  factory ${type.name}.fromJson(Object? json) {`,
    `    final object = _readObject(json, '${type.name}');`,
    `    return ${type.name}(`,
  ];

  for (const field of type.fields) {
    lines.push(...renderDartFieldRead(type, field));
  }

  lines.push("    );", "  }", "");
  for (const field of type.fields) {
    lines.push(`  final ${toDartType(field.type)} ${field.name};`);
  }
  lines.push("", "  Map<String, Object?> toJson() => {");
  for (const field of type.fields) {
    const value = scalarTypes.has(field.type)
      ? field.name
      : `${field.name}.toJson()`;
    lines.push(`        '${field.name}': ${value},`);
  }
  lines.push("      };", "}");
  return lines;
}

function renderDartFieldRead(owner, field) {
  const required = [
    "        _readRequired(",
    "          object,",
    `          '${field.name}',`,
    `          '${owner.name}',`,
    "        ),",
  ];
  let reader;
  switch (field.type) {
    case "string":
      reader = "_readString";
      break;
    case "integer":
      reader = "_readInt";
      break;
    case "boolean":
      reader = "_readBool";
      break;
    default:
      return [
        `      ${field.name}: ${field.type}.fromJson(`,
        ...required,
        "      ),",
      ];
  }

  return [
    `      ${field.name}: ${reader}(`,
    ...required,
    `        '${owner.name}.${field.name}',`,
    "      ),",
  ];
}

function toDartType(type) {
  switch (type) {
    case "integer":
      return "int";
    case "boolean":
      return "bool";
    case "string":
      return "String";
    default:
      return type;
  }
}

function validateDescriptor(descriptor) {
  if (descriptor?.schemaVersion !== 1 || !Array.isArray(descriptor.types)) {
    throw new Error("handshake.json must contain schemaVersion 1 and a types array");
  }

  if (!descriptor.reservedFeatures ||
      Object.keys(descriptor.reservedFeatures).length !== 6 ||
      Object.entries(descriptor.reservedFeatures).some(([key, value]) =>
        !/^[a-zA-Z][a-zA-Z0-9]*$/.test(key) || typeof value !== "string" ||
        !/^[a-zA-Z][a-zA-Z0-9_]*$/.test(value)) ||
      new Set(Object.values(descriptor.reservedFeatures)).size !== 6) {
    throw new Error("handshake.json must define six unique reserved feature names");
  }

  const actualTypes = descriptor.types.map((type) => ({
    name: type?.name,
    kind: type?.kind,
    fields: type?.fields?.map((field) => field?.name) ?? [],
  }));
  if (JSON.stringify(actualTypes) !== JSON.stringify(expectedTypes)) {
    throw new Error(
      "handshake.json must define exactly the handshake metadata contract",
    );
  }

  const knownTypes = new Set([
    ...scalarTypes,
    ...descriptor.types.map((type) => type.name),
  ]);
  for (const type of descriptor.types) {
    if (typeof type.description !== "string" || type.description.length === 0) {
      throw new Error(`${type.name} must have a description`);
    }
    validateTypeParameters(type);
    if (type.kind === "map") {
      if (type.keyType !== "Feature" || type.valueType !== "boolean") {
        throw new Error("EnabledFeatures must map strings to booleans");
      }
      continue;
    }
    for (const field of type.fields) {
      if (!knownTypes.has(field.type)) {
        throw new Error(`${type.name}.${field.name} has an unsupported type`);
      }
      if (
        field.typeArgument !== undefined &&
        !type.typeParameters?.some(
          (parameter) => parameter.name === field.typeArgument,
        )
      ) {
        throw new Error(`${type.name}.${field.name} has an unknown type argument`);
      }
    }
  }
}

function validateTypeParameters(type) {
  if (type.typeParameters === undefined) return;
  if (
    !Array.isArray(type.typeParameters) ||
    type.typeParameters.length !== 1 ||
    type.typeParameters[0]?.name !== "Feature" ||
    type.typeParameters[0]?.constraint !== "string" ||
    type.typeParameters[0]?.default !== "string"
  ) {
    throw new Error(`${type.name} has unsupported type parameters`);
  }
}

function parseArguments(args) {
  let check = false;
  let root = repositoryRoot;

  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];
    if (argument === "--check") {
      check = true;
    } else if (argument === "--root") {
      const value = args[index + 1];
      if (!value) throw new Error("--root requires a path");
      root = resolve(value);
      index += 1;
    } else {
      throw new Error(`Unknown argument: ${argument}`);
    }
  }

  return { check, root };
}

async function main() {
  const options = parseArguments(process.argv.slice(2));
  const drifted = await generateHandshake(options);
  if (options.check && drifted.length > 0) {
    console.error(
      `Generated handshake contracts are out of date:\n${drifted
        .map((path) => `- ${relative(options.root, resolve(options.root, path))}`)
        .join("\n")}\nRun npm run generate:handshake.`,
    );
    process.exitCode = 1;
  } else if (options.check) {
    console.log("Generated handshake contracts are up to date.");
  }
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  await main();
}
