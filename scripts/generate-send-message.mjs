export async function generateSendMessage({
  check = false,
  root = repositoryRoot,
} = {}) {
  const descriptor = await readSendMessageDescriptor(root);
  const outputs = {
    [outputPaths.typescript]: generateTypeScript(descriptor),
    [outputPaths.dart]: generateDart(descriptor),
  };
  const drifted = [];

  for (const [path, generated] of Object.entries(outputs)) {
    const absolutePath = resolve(root, path);
    if (check) {
      let existing;
      try {
        existing = await readFile(absolutePath, "utf8");
      } catch (error) {
        if (error?.code !== "ENOENT") throw error;
      }
      if (existing !== generated) drifted.push(path);
      continue;
    }
    await mkdir(dirname(absolutePath), { recursive: true });
    await writeFile(absolutePath, generated, "utf8");
  }
  return drifted;
}

function validateDescriptor(descriptor) {
  if (descriptor?.schemaVersion !== 1) {
    throw new Error("send-message.json must have schemaVersion 1");
  }
  if (
    descriptor.method !== "POST" ||
    descriptor.path !== "/conversations/:conversationId/messages" ||
    descriptor.operation !== "send"
  ) {
    throw new Error("send-message.json must define POST send-message routing");
  }
  assertNames(descriptor.inputFields, expectedInputFields, "input fields");
  const replyTo = descriptor.inputFields.find((field) => field.name === "replyTo");
  if (replyTo.type !== "MessageReplyReference" || replyTo.presence !== "optional") {
    throw new Error("send-message.json replyTo must be an optional MessageReplyReference");
  }
  assertNames(descriptor.resultFields, expectedResultFields, "result fields");
  assertNames(
    descriptor.reconciliationStatuses,
    ["applied", "replayed"],
    "reconciliation statuses",
  );
  if (descriptor.canonicalRevisionRule !== "createdMessageRevisionOne") {
    throw new Error("send-message.json must require created message revision one");
  }
  if (
    JSON.stringify(descriptor.trustedIdentityAliases) !==
    JSON.stringify(expectedTrustedAliases)
  ) {
    throw new Error("send-message.json trusted identity aliases are incomplete");
  }
  const clientMessageId = descriptor.resultFields[2];
  const message = descriptor.resultFields[3];
  const canonicalRevision = descriptor.resultFields[4];
  if (
    clientMessageId.source !== "input" ||
    message.type !== "Message" ||
    message.source !== "server" ||
    canonicalRevision.type !== "positiveSafeInteger" ||
    canonicalRevision.source !== "server"
  ) {
    throw new Error("send-message.json must define canonical result ownership");
  }
}

function assertNames(values, expected, label) {
  const names = values?.map((value) => value?.name);
  if (JSON.stringify(names) !== JSON.stringify(expected)) {
    throw new Error(
      "send-message.json must define exactly these " +
        label +
        ": " +
        expected.join(", "),
    );
  }
}

function normalizeAlias(alias) {
  return alias.replaceAll(/[^a-zA-Z0-9]/g, "").toLowerCase();
}

function parseArguments(args) {
  let check = false;
  let root = repositoryRoot;
  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];
    if (argument === "--check") {
      check = true;
    } else if (argument === "--root") {
      const value = args[index + 1];
      if (!value) throw new Error("--root requires a path");
      root = resolve(value);
      index += 1;
    } else {
      throw new Error("Unknown argument: " + argument);
    }
  }
  return { check, root };
}

async function main() {
  const options = parseArguments(process.argv.slice(2));
  const drifted = await generateSendMessage(options);
  if (options.check && drifted.length > 0) {
    console.error(
      `Generated send-message contracts are out of date:\n${drifted
        .map((path) => `- ${relative(options.root, resolve(options.root, path))}`)
        .join("\n")}\nRun npm run generate:send-message.`,
    );
    process.exitCode = 1;
  } else if (options.check) {
    console.log("Generated send-message contracts are up to date.");
  }
}

