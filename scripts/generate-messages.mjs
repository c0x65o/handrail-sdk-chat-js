export async function generateMessages({
  check = false,
  root = repositoryRoot,
} = {}) {
  const descriptor = await readMessageDescriptor(root);
  const outputs = {
    [outputPaths.typescript]: generateTypeScript(descriptor),
    [outputPaths.dart]: generateDart(descriptor),
  };
  const drifted = [];

  for (const [path, generated] of Object.entries(outputs)) {
    const absolutePath = resolve(root, path);
    if (check) {
      let existing;
      try {
        existing = await readFile(absolutePath, "utf8");
      } catch (error) {
        if (error?.code !== "ENOENT") throw error;
      }
      if (existing !== generated) drifted.push(path);
      continue;
    }

    await mkdir(dirname(absolutePath), { recursive: true });
    await writeFile(absolutePath, generated, "utf8");
  }

  return drifted;
}

function validateDescriptor(descriptor) {
  if (descriptor?.schemaVersion !== 1) {
    throw new Error("message.json must use schemaVersion 1");
  }
  const signature = {
    content: {
      name: descriptor.content?.name,
      formats: descriptor.content?.formats,
      fields: descriptor.content?.fields?.map(fieldSignature),
    },
    forwardedAuthor: {
      name: descriptor.forwardedAuthor?.name,
      fields: descriptor.forwardedAuthor?.fields?.map(constrainedFieldSignature),
      maximumDisplayNameLength: descriptor.forwardedAuthor?.fields?.find(
        (field) => field?.name === "displayName",
      )?.maximumLength,
    },
    forwardedSnapshot: {
      name: descriptor.forwardedSnapshot?.name,
      fields: descriptor.forwardedSnapshot?.fields?.map(constrainedFieldSignature),
      snapshotSemantics: descriptor.forwardedSnapshot?.snapshotSemantics,
      rawHtml: descriptor.forwardedSnapshot?.rawHtml,
      trustedOrPrivateData: descriptor.forwardedSnapshot?.trustedOrPrivateData,
    },
    replyReference: {
      name: descriptor.replyReference?.name,
      fields: descriptor.replyReference?.fields?.map(
        (field) => `${field?.name}:${field?.type}:${field?.presence}`,
      ),
      maximumIdUtf8Bytes: descriptor.replyReference?.fields?.[0]?.maximumUtf8Bytes,
      idValidation: descriptor.replyReference?.fields?.[0]?.validation,
      defaults: descriptor.replyReference?.fields?.map((field) => Object.hasOwn(field, "default")),
      forbiddenFields: descriptor.replyReference?.forbiddenFields,
    },
    mentions: {
      name: descriptor.mentions?.name,
      variants: descriptor.mentions?.variants?.map(
        (variant) =>
          `${variant?.name}:${variant?.wireType}:${variant?.field?.name}:${variant?.field?.type}`,
      ),
    },
    attachmentReference: `${descriptor.attachmentReference?.name}:${descriptor.attachmentReference?.field?.name}:${descriptor.attachmentReference?.field?.type}`,
    block: `${descriptor.block?.name}:${descriptor.block?.fields?.map((field) => `${field?.name}:${field?.type}`).join(",")}`,
    author: `${descriptor.author?.name}:${descriptor.author?.wireType}:${descriptor.author?.field?.name}:${descriptor.author?.field?.type}`,
    revision: descriptor.revision?.fields?.map(constrainedFieldSignature),
    threadSummaryFacts: {
      name: descriptor.threadSummaryFacts?.name,
      fields: descriptor.threadSummaryFacts?.fields?.map(
        (field) => `${field?.name}:${field?.type}:${field?.presence}:${JSON.stringify(field?.minimum) ?? "*"}`,
      ),
    },
    threadSummary: descriptor.threadSummary?.fields?.map(constrainedFieldSignature),
    normalizedThreadSummary: {
      name: descriptor.normalizedThreadSummary?.name,
      fields: descriptor.normalizedThreadSummary?.fields?.map(
        (field) => `${field?.name}:${field?.type}:${field?.presence}:${JSON.stringify(field?.minimum) ?? "*"}`,
      ),
    },
    message: {
      name: descriptor.message?.name,
      sharedFields: descriptor.message?.sharedFields?.map(fieldSignature),
      states: descriptor.message?.states?.map(
        (state) => `${state?.name}:${state?.content}:${state?.deletionFields}`,
      ),
      deletionFields: descriptor.message?.deletionFields?.map(
        (field) => `${field?.name}:${field?.type}`,
      ),
    },
    composition: {
      name: descriptor.composition?.name,
      fields: descriptor.composition?.fields?.map(fieldSignature),
      serverOwnedFields: descriptor.composition?.serverOwnedFields,
    },
  };
  if (JSON.stringify(signature) !== JSON.stringify(expectedShape)) {
    throw new Error("message.json does not match the supported message contract shape");
  }
}

function fieldSignature(field) {
  return `${field?.name}:${field?.type}:${field?.presence ?? "required"}`;
}

function constrainedFieldSignature(field) {
  return `${fieldSignature(field)}:${JSON.stringify(field?.minimum) ?? "*"}`;
}

async function runCli() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const rootIndex = args.indexOf("--root");
  const root = rootIndex === -1 ? repositoryRoot : resolve(args[rootIndex + 1]);
  if (rootIndex !== -1 && !args[rootIndex + 1]) {
    throw new Error("--root requires a path");
  }
  const unknown = args.filter(
    (argument, index) =>
      argument !== "--check" &&
      argument !== "--root" &&
      index !== rootIndex + 1,
  );
  if (unknown.length > 0) {
    throw new Error(`Unknown arguments: ${unknown.join(", ")}`);
  }

  const drifted = await generateMessages({ check, root });
  if (check && drifted.length > 0) {
    for (const path of drifted) {
      console.error(`Generated message contract is stale: ${relative(root, resolve(root, path))}`);
    }
    process.exitCode = 1;
  } else if (check) {
    console.log("Generated message contracts are up to date.");
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await runCli();
}
